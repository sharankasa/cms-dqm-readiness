#!/usr/bin/env python3
"""
translate.py — the two-backend slicing check: translate the portable core SQL (DuckDB dialect, sql/core/*.sql) to Athena
(Trino) with SQLGlot, and write sql/athena/generated/*.sql for athena_run.py.

  python3 translate.py            # regenerate
  python3 translate.py --check    # exit 1 if the generated files are out of date

Fix-ups applied after SQLGlot, all mechanical and listed here:
  1. SHA256 takes VARBINARY in Trino: SHA256(x) -> SHA256(TO_UTF8(x)) (SQLGlot already adds
     TO_HEX/LOWER for the hex output).
  2. Every CTAS gets Athena storage properties and a per-run location:
     CREATE TABLE t AS ... -> CREATE TABLE t WITH (format='PARQUET', write_compression='SNAPPY',
     external_location='{loc}/t/') AS ...
Placeholders ({lookback_hours}, {lookahead_hours}, {filter_off}) are kept for the runner to fill.
"""
import argparse
import hashlib
import os
import re
import sys

import sqlglot
from sqlglot import exp

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from common import sql_file  # noqa: E402

# Sentinels must survive SQLGlot's pretty-printing as single tokens (a bracketed expression was
# split across lines and silently left in place on the first Athena run, 2026-10-09: the filter
# was off). A bare identifier stays one token.
SENTINELS = {"lookback_hours": "987654321", "lookahead_hours": "987654322", "filter_off": "dqm_sentinel_filter_off"}
FILES = ["core/20_slice.sql", "core/30_filter_hash.sql"]


def translate(rel):
    out = []
    for stmt in sql_file(rel, **SENTINELS):
        tree = sqlglot.parse_one(stmt, read="duckdb")
        # innermost first (reversed breadth-first order), so nested SHA256 calls are all fixed
        for node in reversed(list(tree.find_all(exp.SHA2))):
            node.set("this", exp.Anonymous(this="TO_UTF8", expressions=[node.this.copy()]))
        sql = tree.sql(dialect="athena", pretty=True)
        sql = re.sub(r"^CREATE TABLE (\w+) AS\b",
                     lambda m: (f"CREATE TABLE {m.group(1)}\nWITH (format = 'PARQUET', write_compression = 'SNAPPY', "
                                f"external_location = '{{loc}}/{m.group(1)}/') AS"), sql)
        for k, v in SENTINELS.items():
            sql = sql.replace(v, "{" + k + "}")
        if re.search(r"98765432\d|dqm_sentinel", sql):
            sys.exit(f"sentinel left in {rel}")
        out.append(sql + ";")
    src = open(os.path.join(HERE, "sql", rel)).read()
    header = (f"-- GENERATED by translate.py from sql/{rel} (sha256 {hashlib.sha256(src.encode()).hexdigest()[:16]}), "
              f"SQLGlot {sqlglot.__version__}, DuckDB -> Athena.\n-- Do not edit: edit the core file and regenerate.\n\n")
    return header + "\n\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    gdir = os.path.join(HERE, "sql", "athena", "generated")
    os.makedirs(gdir, exist_ok=True)
    stale = []
    for rel in FILES:
        text = translate(rel)
        path = os.path.join(gdir, os.path.basename(rel))
        if a.check:
            if not os.path.exists(path) or open(path).read() != text:
                stale.append(path)
        else:
            open(path, "w").write(text)
            print("wrote", os.path.relpath(path, HERE))
    if stale:
        sys.exit(f"out of date: {stale}")


if __name__ == "__main__":
    main()
