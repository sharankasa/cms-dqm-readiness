#!/usr/bin/env python3
"""
make_table3_figure5.py: build the manuscript's Table 3 (impact of each mapping variant and scenario) and
Figure 5 (rate differences with 95% CIs) from the aggregate R2 outputs written by
pipeline/readiness/r2_analysis.py. Reads only aggregate files (rates.csv, membership.csv); counts from
1 to 9 are already masked as <10 there.

  python3 manuscript/scripts/make_table3_figure5.py                        (latest r2-analysis run)
  python3 manuscript/scripts/make_table3_figure5.py --run results/r2-analysis-20261014T164159Z

Writes manuscript/tables/table3.md and manuscript/figures/figure5.{png,svg}.
"""
import argparse
import csv
import glob
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

# (set name, label, exploratory?) in table order; sets missing from the run are skipped
SETS = [
    ("COHORT_A", "Baseline (mapping a)", False),
    ("CHANGED_B", "Mapping b, conservative", False),
    ("CHANGED_C", "Mapping c, liberal", False),
    ("CHANGED_D", "Mapping d, model-proposed", False),
    ("SCENARIO_STATUS_LOWER", "Medication status corrected, lower bound", False),
    ("SCENARIO_STATUS_UPPER", "Medication status corrected, upper bound", False),
    ("SCENARIO_TERM_TYPE_1", "Brand drug codes, injected 1%", False),
    ("SCENARIO_TERM_TYPE_10", "Brand drug codes, injected 10%", False),
    ("SCENARIO_TERM_TYPE_50", "Brand drug codes, injected 50%", False),
    ("SCENARIO_MISSING_LINKS_1", "Diagnosis links removed, injected 1%", False),
    ("SCENARIO_MISSING_LINKS_10", "Diagnosis links removed, injected 10%", False),
    ("SCENARIO_MISSING_LINKS_50", "Diagnosis links removed, injected 50%", False),
    ("SCENARIO_NATURAL_LINKS", "Diagnosis links as exported", False),
    ("SCENARIO_NATURAL_UNITS", "Glucose units as exported", False),
    ("SCENARIO_NATURAL_PROFILES", "Profiles as exported, results and administrations", False),
    ("SCENARIO_NATURAL_CODES", "Codes as exported (local), results and administrations", False),
    ("SCENARIO_GLUCOSE_LAB_ONLY", "Laboratory glucose only (registered sensitivity)", False),
    ("SCENARIO_ICU_GLUCOSE_UNIT_ASSUMED", "Bedside glucose unit assigned (exploratory)", True),
    ("SCENARIO_OBSERVATION_AS_INPATIENT", "Observation stays typed as inpatient (exploratory)", True),
]

POP = {"CMS816": ("denominator", "numerator"), "CMS871": ("initial population", "numerator")}


def latest_run():
    runs = sorted(glob.glob(os.path.join(ROOT, "results", "r2-analysis-*")))
    if not runs:
        raise SystemExit("no r2-analysis run found")
    return runs[-1]


def read(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def f(x, nd=2):
    v = float(x)
    s = f"{v:.{nd}f}"
    if s.startswith("-0.") and float(s) == 0:
        s = s[1:]
    return s.replace("-", "−")


def signed(x, nd=2):
    s = f(x, nd)
    return s if s.startswith("−") or float(x) == 0 or s == f"{0:.{nd}f}" else "+" + s


def ci(lo, hi, nd=2):
    return f"{signed(lo, nd)} to {signed(hi, nd)}"


def num(x):
    if x in ("", None):
        return ""
    if x.startswith("<"):
        return x
    return f"{int(float(x)):,}"


def moved(mem, s, m, pop):
    r = mem.get((s, m, pop))
    if not r:
        return "0 / 0"
    return f"{num(r['entering'])} / {num(r['leaving'])}"


def group(row):
    s, _, expl = row
    if expl:
        return "exploratory"
    for k in ("CHANGED_", "STATUS", "TERM_TYPE", "LINKS", "NATURAL_UNITS", "NATURAL_PROFILES", "NATURAL_CODES"):
        if k in s:
            return "natural" if k.startswith("NATURAL_") else k
    return s


def diff(r):
    if r["scenario_rate"] in ("", None):
        return "Not defined"
    d = float(r["scenario_rate"]) - float(r["baseline_rate"])
    if d == 0 and float(r["d_lo"]) == 0 and float(r["d_hi"]) == 0:
        return "No stay changed"
    return f"{signed(d)} ({ci(r['d_lo'], r['d_hi'])})"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run")
    a = ap.parse_args()
    run = a.run if a.run else latest_run()
    if not os.path.isabs(run):
        run = os.path.join(ROOT, run)
    rates = {(r["set"], r["measure"]): r for r in read(os.path.join(run, "rates.csv"))}
    mem = {(r["set"], r["measure"], r["pop"]): r for r in read(os.path.join(run, "membership.csv"))}
    present = [s for s in SETS if (s[0], "CMS816") in rates]
    missing = [s[1] for s in SETS if (s[0], "CMS816") not in rates]

    out = []
    out.append(f"<!-- generated by manuscript/scripts/make_table3_figure5.py from {os.path.relpath(run, ROOT)}; do not edit by hand -->")
    out.append("")
    out.append("**Table 3.** Effect of each medication mapping and data scenario on CMS816 and CMS871 in the 2017–2019 cohort "
               "(88,234 stays). Only stays whose input changed were re-evaluated; all others keep their baseline result. "
               "Entering / leaving: stays added to or removed from the population relative to baseline. CMS816 rates with Wilson "
               "95% CIs; CMS871 rates and all differences with 95% CIs from a paired stay-level bootstrap (2,000 resamples). "
               "Counts from 1 to 9 are shown as <10.")
    out.append("")
    out.append("*A. CMS816, severe hypoglycemia (stays with an event per 100 denominator stays)*")
    out.append("")
    out.append("| Variant or scenario | Stays re-run | Denominator | Denominator entering / leaving | Events | Events entering / leaving | Rate, % (95% CI) | Difference, points (95% CI) |")
    out.append("|---|---:|---:|---:|---:|---:|---:|---:|")
    for s, label, _ in present:
        r = rates[(s, "CMS816")]
        base = s == "COHORT_A"
        out.append("| " + " | ".join([
            label,
            num(r["rerun_stays"]) if not base else f"{num(r['rerun_stays'])} (all)",
            num(r["scenario_denominator"]),
            "" if base else moved(mem, s, "CMS816", POP["CMS816"][0]),
            num(r["scenario_numerator"]),
            "" if base else moved(mem, s, "CMS816", POP["CMS816"][1]),
            (f"{f(r['scenario_rate'])} ({f(r['scenario_wilson_lo'])}–{f(r['scenario_wilson_hi'])})"
             if r["scenario_rate"] not in ("", None) else "No denominator stays"),
            "Reference" if base else diff(r),
        ]) + " |")
    out.append("")
    out.append("*B. CMS871, severe hyperglycemia (hyperglycemic days per 100 eligible days)*")
    out.append("")
    out.append("| Variant or scenario | Stays re-run | Population | Population entering / leaving | Stays with an event day | Entering / leaving | Event days / eligible days | Rate per 100 days (95% CI) | Difference (95% CI) |")
    out.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for s, label, _ in present:
        r = rates[(s, "CMS871")]
        base = s == "COHORT_A"
        ip = mem.get((s, "CMS871", "initial population"))
        nm = mem.get((s, "CMS871", "numerator"))
        ip_n = num(ip["scenario_stays"]) if ip else "13,302"
        nm_n = num(nm["scenario_stays"]) if nm else "1,400"
        out.append("| " + " | ".join([
            label,
            num(r["rerun_stays"]) if not base else f"{num(r['rerun_stays'])} (all)",
            ip_n,
            "" if base else moved(mem, s, "CMS871", POP["CMS871"][0]),
            nm_n,
            "" if base else moved(mem, s, "CMS871", POP["CMS871"][1]),
            f"{num(r['scenario_numerator'])} / {num(r['scenario_denominator'])}",
            f"{f(r['scenario_rate'])} ({f(r['s_lo'])}–{f(r['s_hi'])})",
            "Reference" if base else diff(r),
        ]) + " |")
    out.append("")
    if missing:
        out.append("Not yet in this run: " + "; ".join(missing) + ".")
        out.append("")

    tdir = os.path.join(ROOT, "manuscript", "tables")
    os.makedirs(tdir, exist_ok=True)
    with open(os.path.join(tdir, "table3.md"), "w") as fh:
        fh.write("\n".join(out))

    try:
        import matplotlib
    except ImportError:
        raise SystemExit("matplotlib is needed to draw the figures: python3 -m pip install --user -r requirements-figures.txt")
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    # As-exported units, profiles and codes: rates fall to zero or lose their denominator; reported in Table 3 only,
    # so the figure keeps a readable scale.
    rows = [s for s in present if s[0] not in ("COHORT_A", "SCENARIO_NATURAL_UNITS", "SCENARIO_NATURAL_PROFILES",
                                               "SCENARIO_NATURAL_CODES")]
    fig, axes = plt.subplots(1, 2, figsize=(10.5, 0.42 * len(rows) + 1.6), sharey=True)
    for ax, m, xl in [(axes[0], "CMS816", "Difference from baseline, percentage points"),
                      (axes[1], "CMS871", "Difference from baseline, per 100 eligible days")]:
        for i, (s, label, expl) in enumerate(rows):
            r = rates[(s, m)]
            d = float(r["scenario_rate"]) - float(r["baseline_rate"])
            lo, hi = float(r["d_lo"]), float(r["d_hi"])
            y = len(rows) - 1 - i
            ax.plot([lo, hi], [y, y], color="black", lw=1.4)
            ax.plot([d], [y], marker="o", ms=6, mfc="white" if expl else "black", mec="black", lw=0)
        for i in range(1, len(rows)):
            if group(rows[i]) != group(rows[i - 1]):
                ax.axhline(len(rows) - i - 0.5, color="0.8", lw=0.6)
        ax.axvline(0, color="0.5", lw=0.8, ls="--")
        ax.set_xlabel(xl, fontsize=9)
        ax.set_title(m, fontsize=10, loc="left")
        ax.tick_params(labelsize=8)
        ax.grid(axis="x", color="0.9", lw=0.6)
        for sp in ("top", "right"):
            ax.spines[sp].set_visible(False)
    axes[0].set_yticks(range(len(rows)))
    axes[0].set_yticklabels([s[1] for s in reversed(rows)], fontsize=8)
    fig.text(0.01, 0.01, "Filled: registered analyses. Open: exploratory. Lines: 95% CI (paired stay-level bootstrap). "
             "Units, profiles and codes as exported (rates fall to zero) are in Table 3.",
             fontsize=7.5, color="0.3")
    fig.tight_layout(rect=(0, 0.03, 1, 1))
    fdir = os.path.join(ROOT, "manuscript", "figures")
    os.makedirs(fdir, exist_ok=True)
    for ext in ("png", "svg"):
        fig.savefig(os.path.join(fdir, f"figure5.{ext}"), dpi=300 if ext == "png" else None)
    print(f"from {os.path.relpath(run, ROOT)}: {len(present)} sets; missing {len(missing)}")
    print("wrote manuscript/tables/table3.md, manuscript/figures/figure5.png, figure5.svg")


if __name__ == "__main__":
    main()
