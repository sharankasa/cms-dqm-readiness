def read(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def num(x):
    return x if str(x).startswith("<") else f"{int(float(x)):,}"


def pct(a, b):
    return f"{100 * a / b:.1f}" if b else ""


def table1():
    out = ["**Table 1.** Readiness checks derived from the measures: what each requires, where the logic uses it, and "
           "what happens to the measure when it fails. Sources: data requirements generated by fqm-execution from each "
           "measure, and the elements the CQL reads beyond them (Supplementary Methods 10).", "",
           "| Check | Requirement | Used by | If it fails |", "|---|---|---|---|"]
    for _, name, req, used, fail in CHECKS:
        out.append(f"| {name} | {req} | {used} | {fail} |")
    return "\n".join(out) + "\n"


def table2_and_cells():
    exp = {(r["check_id"], r["role"]): r for r in read(os.path.join(R1, "checks_as_exported.csv"))}
    base = {(r["check_id"], r["role"]): r for r in read(os.path.join(R1, "checks_baseline.csv"))}
    out = ["**Supplementary Table S2.** Records failing each check in the 2017–2019 cohort (88,234 stays), as exported and after the "
           "baseline mapping. Every record the measures use is checked: glucose results, administrations of drugs in "
           "either measure's value set, diabetes diagnoses and stay encounters. Only applicable check and record "
           "pairs are shown. For stay encounters the code check asks for any SNOMED CT encounter type (an "
           "observation-typed stay is correctly mapped); whether the type is inpatient is the last row. The two eMAR "
           "checks are specific to MIMIC's medication record and are not changed by mapping.", "",
           "| Check | Records | Records checked | As exported: failing (%) | After mapping: failing (%) |",
           "|---|---|---:|---:|---:|"]
    cells = {}
    for cid, name, *_ in CHECKS:
        for role, rlabel in ROLES:
            e, b = exp.get((cid, role)), base.get((cid, role))
            ne = int(e["records"]) if e else 0
            nb = int(b["records"]) if b else 0
            if ne == 0 and nb == 0:
                continue
            fe, fb = (int(e["flagged"]) if e else 0), (int(b["flagged"]) if b else 0)
            cells[(cid, role)] = (100 * fe / ne if ne else None, 100 * fb / nb if nb else None)
            ex = f"{num(fe)} ({pct(fe, ne)})" if ne else "not applicable (no RxNorm code)"
            out.append(f"| {name} | {rlabel} | {num(max(ne, nb))} | {ex} | {num(fb)} ({pct(fb, nb)}) |")
    return "\n".join(out) + "\n", cells


def table3():
    def groups(key):
        d = {}
        for r in read(os.path.join(RES, S1[key], "by_group.csv")):
            if r["outcome"] == "identical":
                d.setdefault(r["reason"], {})[r["measure"][:6]] = int(r["stays"])
        return d
    s1, fault, batch = groups("s1"), groups("fault"), groups("batch")
    label = {"random": "Random sample", "g1 highest workload": "Highest measure workload",
             "g2 ED or observation just before admission": "Emergency or observation time just before admission",
             "g3 readmission within 24 h": "Readmission within 24 hours",
             "g4 spans a year boundary": "Discharge at a year boundary"}
    ub = lambda n: f"{100 * 3.8415 / (n + 3.8415):.2f}" if n < 10000 else f"{100 * 3.8415 / (n + 3.8415):.4f}"
    out = ["**Table 2.** Stay-level agreement. A stay is identical only if every population (initial population, "
           "denominator, exclusions, numerator) and, for CMS871, both per-stay observations (eligible days and "
           "hyperglycemic days) match. Upper bound: upper limit of the 95% Wilson interval for the discordance rate "
           "(0 discordant). Fewer than 10 stays per measure had no whole-record result (evaluations stopped at the "
           "registered cost cap).", "",
           "| Comparison | Stays | Compared | Identical, CMS816 | Identical, CMS871 | Discordant | 95% upper bound, % |",
           "|---|---|---:|---:|---:|---:|---:|"]
    order = ["random", "g1 highest workload", "g2 ED or observation just before admission", "g3 readmission within 24 h",
             "g4 spans a year boundary"]
    for g in order:
        n = s1[g]["CMS816"]
        first = "Scaled pipeline vs unmodified engine on whole records" if g == order[0] else ""
        out.append(f"| {first} | {label[g]} | {n:,} | {s1[g]['CMS816']:,} "
                   f"| {s1[g]['CMS871']:,} | 0 | {ub(n)} |")
    n = sum(s1[g]["CMS816"] for g in order)
    out.append(f"|  | **All** | **{n:,}** | **{n:,}** | **{n:,}** | **0** | **{ub(n)}** |")
    for name, d in [("Fault test (2 pods and 1 node killed) vs undisturbed run", fault),
                    ("Several stays per engine call vs one", batch)]:
        n816 = sum(v.get("CMS816", 0) for v in d.values())
        n871 = sum(v.get("CMS871", 0) for v in d.values())
        out.append(f"| {name} | All | {n816:,} | {n816:,} | {n871:,} | 0 | {ub(n816)} |")
    out.append(f"| Independent implementation vs engine, whole records | 2,000-stay sample | 1,994 | 1,994 | 1,994 | 0 | {ub(1994)} |")
    out.append(f"| Independent implementation vs engine, slices | 2017–2019 cohort | 88,234 | 88,234 | 88,234 | 0 | {ub(88234)} |")
    return "\n".join(out) + "\n"


def figure4(cells):
    try:
        import matplotlib
    except ImportError:
        raise SystemExit("matplotlib is needed to draw the figures: python3 -m pip install --user -r requirements-figures.txt")
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.colors import LinearSegmentedColormap
    cmap = LinearSegmentedColormap.from_list("w2r", ["#ffffff", "#f4c7a1", "#c8553d", "#6b1d14"])
    rows = [c for c in CHECKS if any((c[0], r) in cells for r, _ in ROLES)]
    fig, axes = plt.subplots(1, 2, figsize=(11.5, 0.42 * len(rows) + 1.9), sharey=True)
    for k, (ax, title) in enumerate(zip(axes, ["As exported", "After mapping"])):
        for i, (cid, name, *_) in enumerate(rows):
            for j, (role, _) in enumerate(ROLES):
                v = cells.get((cid, role), (None, None))[k]
                if v is None:
                    ax.add_patch(plt.Rectangle((j, i), 1, 1, color="#eeeeee", lw=0))
                    ax.text(j + 0.5, i + 0.5, "–", ha="center", va="center", fontsize=7, color="0.6")
                    continue
                ax.add_patch(plt.Rectangle((j, i), 1, 1, color=cmap(min(v, 100) / 100), lw=0))
                txt = "0" if v == 0 else (f"{v:.1f}" if v < 99.95 else "100")
                ax.text(j + 0.5, i + 0.5, txt, ha="center", va="center", fontsize=7, color="white" if v > 55 else "black")
        ax.set_xlim(0, len(ROLES))
        ax.set_ylim(len(rows), 0)
        ax.set_xticks([j + 0.5 for j in range(len(ROLES))])
        ax.set_xticklabels([r[1] for r in ROLES], rotation=30, ha="right", fontsize=7.5)
        ax.set_title(title, fontsize=10, loc="left")
        for sp in ax.spines.values():
            sp.set_visible(False)
        ax.tick_params(length=0)
    axes[0].set_yticks([i + 0.5 for i in range(len(rows))])
    axes[0].set_yticklabels([r[1] for r in rows], fontsize=7.5)
    fig.text(0.01, 0.01, "Cells: % of records failing the check. Grey: check does not apply to that record type.",
             fontsize=7, color="0.3")
    fig.tight_layout(rect=(0, 0.03, 1, 1))
    for ext in ("png", "svg"):
        fig.savefig(os.path.join(FIG, f"figure4.{ext}"), dpi=300 if ext == "png" else None)


