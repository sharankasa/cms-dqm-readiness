def figure2():
    try:
        import matplotlib
    except ImportError:
        raise SystemExit("matplotlib is needed to draw the figures: python3 -m pip install --user -r requirements-figures.txt")
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(10, 7.6))
    ax.set_xlim(0, 100)
    ax.set_ylim(0, 100)
    ax.axis("off")

    def box(x, y, w, h, text, fc="white", bold=False):
        ax.add_patch(plt.Rectangle((x, y), w, h, fc=fc, ec="black", lw=0.9))
        ax.text(x + w / 2, y + h / 2, text, ha="center", va="center", fontsize=7.8, linespacing=1.35,
                fontweight="bold" if bold else "normal")

    def arrow(x1, y1, x2, y2):
        ax.annotate("", xy=(x2, y2), xytext=(x1, y1), arrowprops=dict(arrowstyle="->", lw=0.9))

    MX, MW, RX, RW = 14, 36, 62, 36
    mid = MX + MW / 2
    box(MX, 86, MW, 11, COHORT["all"], bold=True)
    box(RX, 86, RW, 11, COHORT["s1"], fc="#f2f2f2")
    box(RX, 72, RW, 9, COHORT["full"], fc="#f2f2f2")
    arrow(MX + MW, 91.5, RX, 91.5)
    arrow(MX + MW, 88, RX, 78)
    box(MX, 70, MW, 7, COHORT["linked"])
    arrow(mid, 86, mid, 77)
    box(RX, 52, RW, 14, COHORT["excluded"], fc="#f2f2f2")
    box(MX, 40, MW, 9, COHORT["cohort"], bold=True)
    arrow(mid, 70, mid, 49)
    arrow(mid, 59, RX, 59)
    box(RX, 25, RW, 9, COHORT["obs"], fc="#f2f2f2")
    box(MX, 17, MW, 6, COHORT["inpt"])
    arrow(mid, 40, mid, 23)
    arrow(mid, 29.5, RX, 29.5)
    box(2, 1, 40, 10, COHORT["cms816"])
    box(52, 1, 46, 10, COHORT["cms871"])
    arrow(mid - 4, 17, 22, 11)
    arrow(mid + 4, 17, 75, 11)
