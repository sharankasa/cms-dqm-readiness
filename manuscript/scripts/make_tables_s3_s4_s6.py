#!/usr/bin/env python3
"""
make_tables_s3_s4_s6.py: Supplementary Tables S3 (detection of injected problems by the readiness checks),
S4 (measure components that changed under each mapping variant and scenario) and S6 (model-proposed
medication mapping against the reviewer), from aggregate result files only.

  python3 manuscript/scripts/make_tables_s3_s4_s6.py

Reads results/r1-inject-*/detection.csv, r2-analysis-*/components.csv,
model-mapping-compare-r1*/ (05-08 CSVs) and model-mapping-r1-*/run.json.
Writes manuscript/tables/table_s3.md, table_s4.md, table_s6.md.
"""
import csv
import glob
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "results")
OUT = os.path.join(ROOT, "manuscript", "tables")


def latest(pattern):
    hits = sorted(glob.glob(os.path.join(RES, pattern)))
    if not hits:
        raise SystemExit(f"nothing matches {pattern} under {RES}")
    return hits[-1]


def rows(path):
    return list(csv.DictReader(open(path)))


def n(x):
    return x if not str(x).strip().lstrip("-").isdigit() else f"{int(x):,}"


def header(script_inputs):
    return f"<!-- generated by manuscript/scripts/make_tables_s3_s4_s6.py from {script_inputs}; do not edit by hand -->"


PROBLEMS = [
    ("units", "Glucose result converted to mmol/L", "Glucose value comparable in mg/dL"),
    ("profiles", "QI-Core profile removed", "QI-Core profile declared"),
    ("unmapped-codes", "Standard code removed (LOINC for results, RxNorm for administrations)", "Code in the measure's value set"),
    ("term-type", "Drug code moved to the brand level", "Drug code at the value set's term level"),
    ("missing-links", "Encounter's links to its diagnoses removed", "Encounter linked to its diagnoses"),
    ("status", "Status set to unknown", "Status the measure accepts"),
    ("timing", "Time element removed", "Time element present"),
]


def table_s3():
    f = os.path.join(latest("r1-inject-*"), "detection.csv")
    d = {(r["type"], r["rate_pct"]): r for r in rows(f)}
    out = [header(os.path.relpath(f, ROOT)), "",
           "**Supplementary Table S3.** Detection of injected problems by the readiness checks in the 2017–2019 "
           "cohort. Each problem was injected into a random 1%, 10% or 50% of the records it applies to; a record "
           "counts as detected when the check for that problem flags it. Recall is detected injected records over "
           "injected records; precision is detected injected records over all flagged records. For glucose units, "
           "the 211,894 results that already failed the check after mapping (bedside results without a unit) are "
           "flagged at every rate and lower precision; every injected result was still found.", "",
           "| Injected problem | Check | Rate | Records injected | Records flagged | Injected and flagged | Recall | Precision |",
           "|---|---|---:|---:|---:|---:|---:|---:|"]
    for key, label, check in PROBLEMS:
        for rate in ("1", "10", "50"):
            r = d[(key, rate)]
            out.append(f"| {label} | {check} | {rate}% | {n(r['injected'])} | {n(r['flagged'])} | "
                       f"{n(r['flagged_injected'])} | {float(r['recall']):.2f} | {float(r['precision']):.2f} |")
    return out


SETS = [
    ("CHANGED_B", "Mapping b, conservative"),
    ("CHANGED_C", "Mapping c, liberal"),
    ("CHANGED_D", "Mapping d, model-proposed"),
    ("SCENARIO_STATUS_LOWER", "Medication status corrected, lower bound"),
    ("SCENARIO_STATUS_UPPER", "Medication status corrected, upper bound"),
    ("SCENARIO_TERM_TYPE_1", "Brand drug codes, injected 1%"),
    ("SCENARIO_TERM_TYPE_10", "Brand drug codes, injected 10%"),
    ("SCENARIO_TERM_TYPE_50", "Brand drug codes, injected 50%"),
    ("SCENARIO_MISSING_LINKS_1", "Diagnosis links removed, injected 1%"),
    ("SCENARIO_MISSING_LINKS_10", "Diagnosis links removed, injected 10%"),
    ("SCENARIO_MISSING_LINKS_50", "Diagnosis links removed, injected 50%"),
    ("SCENARIO_NATURAL_LINKS", "Diagnosis links as exported"),
    ("SCENARIO_NATURAL_UNITS", "Glucose units as exported"),
    ("SCENARIO_NATURAL_PROFILES", "Profiles as exported"),
    ("SCENARIO_NATURAL_CODES", "Codes as exported (local)"),
    ("SCENARIO_GLUCOSE_LAB_ONLY", "Laboratory glucose only (registered sensitivity)"),
    ("SCENARIO_ICU_GLUCOSE_UNIT_ASSUMED", "Bedside glucose unit assigned (exploratory)"),
    ("SCENARIO_OBSERVATION_AS_INPATIENT", "Observation stays typed as inpatient (exploratory)"),
]


def table_s4():
    f = os.path.join(latest("r2-analysis-*"), "components.csv")
    data = rows(f)
    out = [header(os.path.relpath(f, ROOT)), "",
           "**Supplementary Table S4.** Parts of each measure that changed under each mapping variant and data "
           "scenario, compared with the baseline. Each entry is a named expression in CMS's measure logic, with the "
           "number of stays whose value for that expression changed. Counts from 1 to 9 are shown as <10. Stays are "
           "re-run only where their records change, so expressions that did not change are not listed.", "",
           "| Mapping or scenario | Measure | Parts of the measure that changed (stays) |", "|---|---|---|"]
    for key, label in SETS:
        for measure in ("CMS816", "CMS871"):
            parts = [r for r in data if r["set"] == key and r["measure"] == measure]
            if not parts:
                continue
            cell = "; ".join(f"{r['definition']} ({n(r['moved_stays_where_changed'])})" for r in parts)
            out.append(f"| {label} | {measure} | {cell} |")
    return out


PARTS = {
    "A": "Excluded codes, high volume (audit round 1)",
    "B": "Excluded codes, random low-volume sample (audit round 1)",
    "C": "Product code (NDC) not mapped",
    "D": "No product code",
    "E": "Mixture containing a value-set drug",
    "F": "ICU infusion item",
}


def table_s6():
    cmp_dir = latest("model-mapping-compare-r1*")
    run = json.load(open(os.path.join(cmp_dir, "run.json")))
    stamp = run.get("params", run).get("model_out", "").rstrip("/").split("-")[-1]
    model_run = [d for d in glob.glob(os.path.join(RES, "model-mapping-r1-*")) if d.endswith(stamp)]
    m = json.load(open(os.path.join(model_run[0], "run.json"))) if model_run else {}

    def find(cols):
        for f in sorted(glob.glob(os.path.join(cmp_dir, "*.csv"))):
            r = rows(f)
            if r and all(c in r[0] for c in cols):
                return r
        raise SystemExit(f"no CSV in {cmp_dir} with {cols}")

    health = find(["entries", "answered", "unparsed"])[0]
    det = {r["part"][0]: r for r in find(["both_yes", "model_missed", "model_extra"])}
    conf = find(["confidence", "measure_equivalent", "same_product"])
    rbe = find(["auto_accepted_high", "left_for_review"])[0]
    agg = {}
    for r in conf:
        a = agg.setdefault(r["part"][0], [0, 0])
        a[0] += int(r["entries"])
        a[1] += int(r["measure_equivalent"])
    out = [header(os.path.relpath(cmp_dir, ROOT)), "",
           "**Supplementary Table S6.** Model-proposed medication mapping (mapping d) against the reviewer, first "
           "audit round. The model (gpt-oss-120b, run in the author's own cloud account with invocation logging "
           "off) answered the same question as the reviewer for each worklist entry, choosing only among RxNorm "
           "candidates, without seeing the reviewer's decisions. \"Same decision for the measures\": both excluded "
           "the entry, or both included it with the same CMS816 and CMS871 value-set membership (for mixtures, the "
           "same keep or drop). Counts are of medication codes, not patients.", "",
           "| Entry type | Entries | Reviewer included | Model also included | Model left out | Model added | Same decision for the measures (%) |",
           "|---|---:|---:|---:|---:|---:|---:|"]
    tot = [0] * 6
    for p, label in PARTS.items():
        d = det[p]
        inc = int(d["both_yes"]) + int(d["model_missed"])
        e, eq = agg[p]
        vals = [e, inc, int(d["both_yes"]), int(d["model_missed"]), int(d["model_extra"]), eq]
        tot = [a + b for a, b in zip(tot, vals)]
        out.append(f"| {label} | {n(e)} | {n(inc)} | {n(d['both_yes'])} | {n(d['model_missed'])} | "
                   f"{n(d['model_extra'])} | {n(eq)} ({100 * eq / e:.1f}) |")
    out.append(f"| **All entries** | {n(tot[0])} | {n(tot[1])} | {n(tot[2])} | {n(tot[3])} | {n(tot[4])} | "
               f"{n(tot[5])} ({100 * tot[5] / tot[0]:.1f}) |")
    ab = [agg[p] for p in "AB"]
    cf = [agg[p] for p in "CDEF"]
    e1, q1 = sum(x[0] for x in ab), sum(x[1] for x in ab)
    e2, q2 = sum(x[0] for x in cf), sum(x[1] for x in cf)
    out += ["", f"Excluded codes (first two rows): same decision for {n(q1)} of {n(e1)} ({100 * q1 / e1:.1f}%). "
                f"Entries needing judgment (the other four rows): {n(q2)} of {n(e2)} ({100 * q2 / e2:.1f}%)."]
    out += ["", "| By the model's stated confidence | Entries | Same decision for the measures (%) |", "|---|---:|---:|"]
    byc = {}
    for r in conf:
        c = byc.setdefault(r["confidence"] or "none", [0, 0])
        c[0] += int(r["entries"])
        c[1] += int(r["measure_equivalent"])
    for c in ("high", "medium", "low", "none"):
        if c in byc:
            e, eq = byc[c]
            out.append(f"| {c.capitalize()} | {n(e)} | {n(eq)} ({100 * eq / e:.1f}) |")
    mins = float(m.get("wall_seconds", 0)) / 60
    out += ["",
            f"Run: {n(health['entries'])} entries, {n(health['answered'])} answered, {health['unparsed']} unparsed, "
            f"{health['errors']} errors, {health['codes_rejected_by_rxnorm_check']} proposed codes rejected by the "
            f"RxNorm check; {mins:.1f} minutes with four parallel requests; "
            f"{n(m.get('input_tokens', 0))} input and {n(m.get('output_tokens', 0))} output tokens; estimated cost "
            f"US${float(m.get('estimated_cost_usd', 0)):.2f}.",
            "",
            f"Review by exception: accepting every high-confidence answer without review would have left "
            f"{n(rbe['left_for_review'])} of {n(rbe['entries'])} entries for a person, but kept "
            f"{n(rbe['accepted_but_wrong_for_measures'])} answers that change a measure, covering at least "
            f"{n(rbe['wrong_accepted_administrations_10plus'])} administrations (codes with 10 or more "
            f"administrations only)."]
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, fn in (("table_s3.md", table_s3), ("table_s4.md", table_s4), ("table_s6.md", table_s6)):
        lines = fn()
        open(os.path.join(OUT, name), "w").write("\n".join(lines) + "\n")
        print(f"wrote manuscript/tables/{name} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
