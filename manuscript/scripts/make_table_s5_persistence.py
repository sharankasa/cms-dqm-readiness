#!/usr/bin/env python3
"""
make_table_s5_persistence.py: Supplementary Table S5, the registered 2020-2022 persistence check (registration §7),
from the aggregate output of pipeline/cohort/20_persistence_2020_2022.sql.

  python3 manuscript/scripts/make_table_s5_persistence.py [--run results/persistence-2020-2022-<stamp>]

Writes manuscript/tables/table_s5.md.
"""
import argparse
import csv
import glob
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def find(run, need):
    for f in sorted(glob.glob(os.path.join(run, "*.csv"))):
        rows = list(csv.DictReader(open(f)))
        if rows and all(c in rows[0] for c in need):
            return {r["year_group"]: r for r in rows}
    raise SystemExit(f"no CSV in {run} with {need}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run")
    a = ap.parse_args()
    runs = sorted(d for d in glob.glob(os.path.join(ROOT, "results", "persistence-2020-2022-*"))
                  if len(glob.glob(os.path.join(d, "*.csv"))) >= 3)
    run = a.run or (runs[-1] if runs else None)
    if not run:
        raise SystemExit("no complete persistence run found")
    run = run if os.path.isabs(run) else os.path.join(ROOT, run)
    adm = find(run, ["admissions", "pct_observation_type"])
    lab = find(run, ["lab_glucose_results"])
    bed = find(run, ["bedside_glucose_results"])
    n = lambda x: f"{int(x):,}"
    rows = [
        ("Admissions (COVID-19 admissions excluded)", "admissions", adm, n),
        ("Observation-type admissions, %", "pct_observation_type", adm, str),
        ("Admissions with an emergency-department stay", "admissions_with_ed_stay", adm, n),
        ("Emergency-department stay ends after the admission time, % of those", "pct_ed_ends_after_admission", adm, str),
        ("Laboratory glucose results", "lab_glucose_results", lab, n),
        ("Laboratory glucose results in mg/dL, %", "pct_mg_dl", lab, str),
        ("Bedside (ICU) glucose results with a numeric value", "bedside_glucose_results", bed, n),
        ("Bedside glucose results without a unit, %", "pct_no_unit", bed, str),
    ]
    out = [f"<!-- generated by manuscript/scripts/make_table_s5_persistence.py from {os.path.relpath(run, ROOT)}; do not edit by hand -->", "",
           "**Supplementary Table S5.** Source-data patterns behind the readiness problems in MIMIC-IV 3.1, admissions "
           "whose possible years lie within 2017–2019 and within 2020–2022 (registered persistence check; SQL only, "
           "no measure run). Bedside glucose: ICU items 225664 and 226537; laboratory glucose: items 50931 and 50809.", "",
           "| Pattern | 2017–2019 | 2020–2022 |", "|---|---:|---:|"]
    for label, col, d, f in rows:
        out.append(f"| {label} | {f(d['2017-2019'][col])} | {f(d['2020-2022'][col])} |")
    os.makedirs(os.path.join(ROOT, "manuscript", "tables"), exist_ok=True)
    open(os.path.join(ROOT, "manuscript", "tables", "table_s5.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out[2:]))


if __name__ == "__main__":
    main()
